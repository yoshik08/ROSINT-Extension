// Builds both extensions from extension/shared/. The shared modules import the
// website's own archive/restriction clients from ../../src, so this script
// walks the import graph and emits one classic script per entry point — Chrome
// content scripts and both background pages run without ES module support.
//
// Also writes extension/dist/rosint-<browser>.zip (the whole browser folder,
// manifest.json at the archive root) with a dependency-free ZIP writer.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync, cpSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateRawSync } from 'node:zlib';

const here = dirname(fileURLToPath(import.meta.url));
const extension = resolve(here, '..');
const repo = resolve(extension, '..');
const targets = ['chrome', 'firefox'];
export const entries = [
    { file: 'popup.js', entry: resolve(extension, 'shared/popup.js') },
    { file: 'quiet.js', entry: resolve(extension, 'shared/quietScript.js') },
    { file: 'content.js', entry: resolve(extension, 'shared/content.js') },
    { file: 'background.js', entry: resolve(extension, 'shared/background.js') },
];

const IMPORT = /^import\s+[^;]*?\sfrom\s*['"]([^'"]+)['"];?[ \t]*$/gm;
const EXPORT = /^export\s+(?=(?:async\s+)?(?:function|class|const|let|var)\s)/gm;
const DECL = /^(?:export\s+)?(?:async\s+)?(?:function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm;
const FORBIDDEN = [
    [/import\.meta/, 'import.meta is not valid in a classic script'],
    [/^export\s*\{/m, 're-exports are not supported by this bundler'],
    [/^export\s+default/m, 'default exports are not supported by this bundler'],
    [/\brequire\s*\(/, 'CommonJS require() is not available'],
    [/\bimport\s*\(/, 'dynamic import is not available in content scripts'],
];

export function bundle(entry) {
    const modules = [];
    const visiting = new Set();
    const done = new Set();
    const declarations = new Map();

    function visit(file) {
        if (done.has(file)) return;
        if (visiting.has(file)) throw new Error(`import cycle at ${relative(repo, file)}`);
        visiting.add(file);

        const source = readFileSync(file, 'utf8');
        for (const [pattern, message] of FORBIDDEN) {
            if (pattern.test(source)) throw new Error(`${relative(repo, file)}: ${message}`);
        }

        for (const match of source.matchAll(IMPORT)) {
            const specifier = match[1];
            if (!specifier.startsWith('.')) {
                throw new Error(`${relative(repo, file)}: only relative imports can be bundled (${specifier})`);
            }
            const dependency = resolve(dirname(file), specifier);
            if (!dependency.startsWith(repo)) {
                throw new Error(`${relative(repo, file)}: import escapes the repository (${specifier})`);
            }
            visit(dependency);
        }

        const identifier = relative(repo, file).split('\\').join('/');
        const code = source
            .replace(IMPORT, '')
            .replace(EXPORT, '')
            .replace(/^\s*\n/, '');
        for (const match of code.matchAll(DECL)) {
            const name = match[1];
            if (declarations.has(name) && declarations.get(name) !== identifier) {
                throw new Error(`duplicate top-level "${name}" in ${identifier} and ${declarations.get(name)}`);
            }
            declarations.set(name, identifier);
        }
        modules.push({ identifier, code });
        visiting.delete(file);
        done.add(file);
    }

    visit(entry);
    return {
        sources: modules.map((module) => module.identifier),
        // Each bundle runs in its own function scope. Both content scripts
        // share the page's isolated world, so top-level declarations in one
        // would otherwise collide with the other's and stop it loading.
        code: [
            '// Generated by extension/scripts/build.mjs. Do not edit; edit extension/shared/.',
            '(() => {',
            "'use strict';",
            ...modules.map((module) => `// ---- ${module.identifier} ----\n${module.code.trimEnd()}\n`),
            '})();',
            '',
        ].join('\n'),
    };
}

const CRC_TABLE = (() => {
    const table = new Uint32Array(256);
    for (let i = 0; i < 256; i += 1) {
        let value = i;
        for (let bit = 0; bit < 8; bit += 1) {
            value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
        }
        table[i] = value >>> 0;
    }
    return table;
})();

function crc32(buffer) {
    let crc = 0xffffffff;
    for (const byte of buffer) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8);
    return (crc ^ 0xffffffff) >>> 0;
}

// Fixed entry timestamps make the packages byte-for-byte reproducible, so a
// store reviewer rebuilding from source gets the same archive. Override with
// SOURCE_DATE_EPOCH (seconds) like other reproducible builds.
function buildDate() {
    const epoch = Number(process.env.SOURCE_DATE_EPOCH);
    return Number.isFinite(epoch) && epoch > 0 ? new Date(epoch * 1000) : new Date(2026, 0, 1, 0, 0, 0);
}

function dosDateTime(date = buildDate()) {
    const time = (date.getHours() << 11) | (date.getMinutes() << 5) | Math.floor(date.getSeconds() / 2);
    const day = ((date.getFullYear() - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate();
    return { time, day };
}

// Minimal ZIP (deflate, UTF-8 names). Enough for a browser add-on package and
// keeps the build dependency-free.
function zip(files) {
    const { time, day } = dosDateTime();
    const locals = [];
    const centrals = [];
    let offset = 0;

    for (const { name, data } of files) {
        const nameBytes = Buffer.from(name, 'utf8');
        const compressed = deflateRawSync(data);
        const crc = crc32(data);

        const local = Buffer.alloc(30);
        local.writeUInt32LE(0x04034b50, 0);
        local.writeUInt16LE(20, 4);
        local.writeUInt16LE(0x0800, 6);
        local.writeUInt16LE(8, 8);
        local.writeUInt16LE(time, 10);
        local.writeUInt16LE(day, 12);
        local.writeUInt32LE(crc, 14);
        local.writeUInt32LE(compressed.length, 18);
        local.writeUInt32LE(data.length, 22);
        local.writeUInt16LE(nameBytes.length, 26);
        local.writeUInt16LE(0, 28);
        locals.push(local, nameBytes, compressed);

        const central = Buffer.alloc(46);
        central.writeUInt32LE(0x02014b50, 0);
        central.writeUInt16LE(20, 4);
        central.writeUInt16LE(20, 6);
        central.writeUInt16LE(0x0800, 8);
        central.writeUInt16LE(8, 10);
        central.writeUInt16LE(time, 12);
        central.writeUInt16LE(day, 14);
        central.writeUInt32LE(crc, 16);
        central.writeUInt32LE(compressed.length, 20);
        central.writeUInt32LE(data.length, 24);
        central.writeUInt16LE(nameBytes.length, 28);
        central.writeUInt16LE(0, 30);
        central.writeUInt16LE(0, 32);
        central.writeUInt16LE(0, 34);
        central.writeUInt16LE(0, 36);
        central.writeUInt32LE(0, 38);
        central.writeUInt32LE(offset, 42);
        centrals.push(Buffer.concat([central, nameBytes]));

        offset += local.length + nameBytes.length + compressed.length;
    }

    const directory = Buffer.concat(centrals);
    const end = Buffer.alloc(22);
    end.writeUInt32LE(0x06054b50, 0);
    end.writeUInt16LE(files.length, 8);
    end.writeUInt16LE(files.length, 10);
    end.writeUInt32LE(directory.length, 12);
    end.writeUInt32LE(offset, 16);
    return Buffer.concat([...locals, directory, end]);
}

// Everything the manifest can point at, so the package can be checked before it
// is written.
function manifestReferences(manifest) {
    return [
        'manifest.json',
        ...(manifest.action?.default_popup ? [manifest.action.default_popup] : []),
        ...(manifest.background?.service_worker ? [manifest.background.service_worker] : []),
        ...(manifest.background?.scripts ?? []),
        ...(manifest.content_scripts ?? []).flatMap((script) => script.js ?? []),
        ...Object.values(manifest.icons ?? {}),
        ...Object.values(manifest.action?.default_icon ?? {}),
    ];
}

const SKIP_DIRS = new Set(['node_modules', 'tests', 'dist']);
const SKIP_FILE = [/\.map$/, /^\.DS_Store$/, /\.log$/, /\.zip$/];

// Every file in the browser folder, addressed relative to it (forward slashes),
// so the zip root is the folder root.
function listFiles(directory, prefix = '') {
    const files = [];
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
        const name = prefix ? `${prefix}/${entry.name}` : entry.name;
        if (entry.isDirectory()) {
            if (!SKIP_DIRS.has(entry.name)) files.push(...listFiles(resolve(directory, entry.name), name));
            continue;
        }
        if (!entry.isFile() || SKIP_FILE.some((pattern) => pattern.test(entry.name))) continue;
        files.push(name);
    }
    return files;
}

// Everything a reviewer needs to rebuild the packages: the build script, both
// manifests, the shared sources and assets, and every module the bundles
// actually pulled in (walked from the import graph, so nothing is missed).
function sourceArchive(version, bundled) {
    const files = new Set([
        'package.json',
        'README.md',
        'LICENSE',
        'extension/README.md',
        'extension/scripts/build.mjs',
        'extension/chrome/manifest.json',
        'extension/firefox/manifest.json',
        ...bundled,
        ...listFiles(resolve(extension, 'shared')).map((name) => `extension/shared/${name}`),
    ]);
    const present = [...files].filter((name) => existsSync(resolve(repo, name))).sort();
    const archive = zip(present.map((name) => ({ name, data: readFileSync(resolve(repo, name)) })));
    const name = `rosint-source-${version}.zip`;
    for (const existing of readdirSync(resolve(extension, 'dist'))) {
        if (/^rosint-source-.*\.zip$/.test(existing)) rmSync(resolve(extension, 'dist', existing));
    }
    writeFileSync(resolve(extension, 'dist', name), archive);
    console.log(`dist/${name}: ${present.length} files for store source review`);
}

function main() {
    const dist = resolve(extension, 'dist');
    mkdirSync(dist, { recursive: true });

    const versions = new Set(targets.map((target) =>
        JSON.parse(readFileSync(resolve(extension, target, 'manifest.json'), 'utf8')).version));
    if (versions.size !== 1) throw new Error(`manifest versions differ: ${[...versions].join(', ')}`);
    const [version] = versions;
    const bundled = new Set();

    for (const target of targets) {
        const directory = resolve(extension, target);
        const manifest = JSON.parse(readFileSync(resolve(directory, 'manifest.json'), 'utf8'));
        writeFileSync(resolve(directory, 'popup.html'), readFileSync(resolve(extension, 'shared/popup.html')));
        // Static assets (font, icons) are copied fresh so removed files never linger.
        rmSync(resolve(directory, 'assets'), { recursive: true, force: true });
        cpSync(resolve(extension, 'shared/assets'), resolve(directory, 'assets'), { recursive: true });

        for (const entry of entries) {
            const { code, sources } = bundle(entry.entry);
            for (const source of sources) bundled.add(source);
            writeFileSync(resolve(directory, entry.file), code, 'utf8');
            console.log(`${target}/${entry.file}: ${sources.length} modules, ${code.length} bytes`);
        }

        // Package the whole browser folder: manifest.json at the root, then the
        // rest. Tests, node_modules and source maps are excluded by listFiles.
        const names = listFiles(directory).sort();
        const ordered = [
            ...names.filter((name) => name === 'manifest.json'),
            ...names.filter((name) => name !== 'manifest.json'),
        ];
        if (ordered[0] !== 'manifest.json') throw new Error(`${target}: manifest.json is not at the package root`);

        const missing = manifestReferences(manifest).filter((name) => !names.includes(name));
        if (missing.length) throw new Error(`${target}: manifest references missing file(s): ${missing.join(', ')}`);
        const junk = names.filter((name) => /(^|\/)(node_modules|tests)\//.test(name) || /\.map$/.test(name));
        if (junk.length) throw new Error(`${target}: package would include ${junk.join(', ')}`);

        const zipName = `rosint-${target}.zip`;
        const zipPath = resolve(dist, zipName);
        // Replace any older archive for this target, including versioned names.
        for (const existing of readdirSync(dist)) {
            if (new RegExp(`^rosint-${target}(-.*)?\\.zip$`).test(existing)) rmSync(resolve(dist, existing));
        }
        const packaged = zip(ordered.map((name) => ({ name, data: readFileSync(resolve(directory, name)) })));
        writeFileSync(zipPath, packaged);
        if (target === 'firefox') {
            writeFileSync(resolve(dist, 'rosint-firefox.xpi'), packaged);
            console.log('dist/rosint-firefox.xpi: unsigned add-on for temporary installation');
        }
        console.log(`dist/${zipName}: ${ordered.length} files [${ordered.join(', ')}]`);
    }
    sourceArchive(version, bundled);
}

// Importable (the tests bundle without writing anything); builds when run.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

